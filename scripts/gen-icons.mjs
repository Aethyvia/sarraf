// Generates src/components/icons/lucide-shapes.ts from Lucide (ISC licence) using scripts/icon-map.json.
// Run once after changing the map:  npx -p lucide@1.62.0 node scripts/gen-icons.mjs  (or set LUCIDE=/path/to/lucide)
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const lucide = require(process.env.LUCIDE ?? 'lucide');
const map = JSON.parse(readFileSync(new URL('./icon-map.json', import.meta.url)));

const shapes = {};
const groups = [];
for (const [group, icons] of Object.entries(map.groups)) {
  const names = [];
  for (const [name, lucideName] of Object.entries(icons)) {
    const node = lucide.icons[lucideName];
    if (!node) throw new Error(`No Lucide icon ${lucideName}`);
    shapes[name] = node.map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== 'key'))]);
    names.push(name);
  }
  groups.push({ key: group, icons: [...names, ...(map.keepGroups[group] ?? [])] });
}

const out = `// Generated by scripts/gen-icons.mjs from Lucide 1.62.0 (ISC licence, https://lucide.dev). Don't edit by hand.
import type { IconElement } from './shapes';

export const LUCIDE_SHAPES: Record<string, IconElement[]> = ${JSON.stringify(shapes)};

export const LUCIDE_GROUPS = ${JSON.stringify(groups)} as const;
`;
writeFileSync(new URL('../src/components/icons/lucide-shapes.ts', import.meta.url), out);
console.log(`${Object.keys(shapes).length} icons in ${groups.length} groups`);
